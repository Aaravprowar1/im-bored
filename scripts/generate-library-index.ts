/**
 * Writes src/lib/activities/library/index.ts, which imports every library
 * file and parses it. Run after adding a library file:
 *   npx tsx scripts/generate-library-index.ts            (every file)
 *   npx tsx scripts/generate-library-index.ts creative-1 (only the named files)
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "src/lib/activities/library");
const files = readdirSync(dir)
  .filter((f) => /^[a-z]+(\+[a-z]+)?-\d+\.ts$/.test(f))
  .filter((f) => process.argv.length <= 2 || process.argv.slice(2).includes(f.replace(/\.ts$/, "")))
  .sort();

const name = (f: string) => f.replace(/\.ts$/, "").replace(/[+-]/g, "_");
const lines = [
  "// Generated by scripts/generate-library-index.ts. Do not edit by hand.",
  'import type { SeedActivity } from "../seed-data";',
  'import { parseLibrary } from "./parse";',
  ...files.map((f) => `import ${name(f)} from "./${f.replace(/\.ts$/, "")}";`),
  "",
  "const FILES: [string, string][] = [",
  ...files.map((f) => `  ["${f.replace(/\.ts$/, "")}", ${name(f)}],`),
  "];",
  "",
  "export const LIBRARY_ACTIVITIES: SeedActivity[] = FILES.flatMap(([file, text]) => {",
  '  const [category, secondary = null] = file.split("-")[0].split("+") as [SeedActivity["category"], SeedActivity["category"]?];',
  "  return parseLibrary(category, text, file, secondary ?? null);",
  "});",
  "",
];
writeFileSync(join(dir, "index.ts"), lines.join("\n"));
console.log(`Indexed ${files.length} library files.`);
