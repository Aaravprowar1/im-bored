import { SEED_ACTIVITIES } from "./seed-data";

function lit(value: string | number | boolean | null): string {
  if (value === null) return "null";
  if (typeof value === "number") return String(Math.trunc(value));
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${value.replace(/'/g, "''")}'`;
}

/** Idempotent seed: inserts new slugs and refreshes existing seed rows. */
export function buildSeedSql(): string {
  const values = SEED_ACTIVITIES.map((a) =>
    `  (${[
      a.slug,
      a.title,
      a.description,
      a.category,
      a.duration_minutes,
      a.difficulty,
      a.location,
      a.energy_level,
      a.cost_type,
      a.people_type,
      a.xp_reward,
      a.is_chaos,
      a.is_featured,
      a.safety_note,
      a.video_query,
    ]
      .map(lit)
      .join(", ")}, 'published', 'seed', now())`,
  ).join(",\n");

  return `-- Generated by scripts/generate-seed-sql.ts. Do not edit by hand.
-- Safe to run repeatedly: rows are matched on slug. Seed rows that an admin
-- archived stay archived.
insert into public.activities (
  slug, title, description, category, duration_minutes, difficulty, location,
  energy_level, cost_type, people_type, xp_reward, is_chaos, is_featured, safety_note,
  video_query, status, source, published_at
) values
${values}
on conflict (slug) do update set
  title = excluded.title,
  description = excluded.description,
  category = excluded.category,
  duration_minutes = excluded.duration_minutes,
  difficulty = excluded.difficulty,
  location = excluded.location,
  energy_level = excluded.energy_level,
  cost_type = excluded.cost_type,
  people_type = excluded.people_type,
  xp_reward = excluded.xp_reward,
  is_chaos = excluded.is_chaos,
  is_featured = excluded.is_featured,
  safety_note = excluded.safety_note,
  video_query = excluded.video_query
where public.activities.source = 'seed';
`;
}
